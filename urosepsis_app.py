import streamlit as st

st.set_page_config(page_title="Прогноз гестационного уросепсиса", layout="centered")

st.title("Прогнозирование гестационного уросепсиса")
st.markdown("### Модель на основе СРБ и ЛДГ при развитии гестационного пиелонефрита")

st.write("Введите данные пациентки:")

# Ввод данных
crp = st.selectbox("СРБ ≥ 60 мг/л", ["Нет", "Да"])
ldh = st.selectbox("ЛДГ ≥ 189 ЕД/л", ["Нет", "Да"])

# Кодирование
crp_val = 1 if crp == "Да" else 0
ldh_val = 1 if ldh == "Да" else 0

# Расчёт
z = -1.448 + 1.961 * crp_val + 2.162 * ldh_val
prob = 1 / (1 + 2.71828 ** (-z)) * 100

st.markdown("---")
st.subheader("Результат")

if prob >= 67.1:
    st.error(f"**Высокий риск уросепсиса**")
    st.write(f"Вероятность развития уросепсиса: **{prob:.1f}%**")
    st.write("Рекомендуется: усиленное наблюдение, консультация анестезиолога-реаниматолога.")
else:
    st.success(f"**Низкий риск уросепсиса**")
    st.write(f"Вероятность развития уросепсиса: **{prob:.1f}%**")
    st.write("Рекомендуется: стандартное наблюдение.")

# Выпадающее окно с информацией о модели
with st.expander("Информация о модели"):
    st.markdown("""
    **Характеристики прогностической модели**

    | Параметр              | Значение                          |
    |-----------------------|-----------------------------------|
    | **AUC**               | 0,846 (95% ДИ: 0,763–0,928)       |
    | **Чувствительность**  | 76,4%                             |
    | **Специфичность**     | 77,8%                             |
    | **Пороговое значение**| 67,1%                             |
    | **Размер выборки**    | 82 пациентки                      |

    **Факторы риска в модели**

    | Фактор              | Отношение шансов (AOR) | 95% ДИ          | p      |
    |---------------------|------------------------|-----------------|--------|
    | СРБ ≥ 60 мг/л       | 7,11                   | 2,19–23,13      | 0,001  |
    | ЛДГ ≥ 189 ЕД/л      | 8,69                   | 2,63–28,70      | <0,001 |

    **Формула расчёта**

    `P = 1 / (1 + e^(-z)) × 100%`

    `z = -1,448 + 1,961 × X₁ + 2,162 × X₂`

    Где:
    - X₁ — СРБ ≥ 60 мг/л (0 = нет, 1 = да)
    - X₂ — ЛДГ ≥ 189 ЕД/л (0 = нет, 1 = да)
    """)

